#[cfg(test)]
mod tests {
    use super::*;
    use num_bigint::BigUint;

    #[test]
    fn test_constants_are_consistent() {
        let big = |b: &[u8]| BigUint::from_bytes_be(b);
        let (n, p, q) = (big(&N), big(&P), big(&Q));
        assert_eq!(n, &p * &q);
        assert_eq!(&p % 4u32, BigUint::from(3u32));
        assert_eq!(&q % 4u32, BigUint::from(3u32));
        assert_eq!(big(&P_EXP), (&p + 1u32) / 4u32);
        assert_eq!(big(&Q_EXP), (&q + 1u32) / 4u32);
        // CRT coefficients
        assert_eq!(big(&AP) % &p, BigUint::from(1u32));
        assert_eq!(big(&AP) % &q, BigUint::from(0u32));
        assert_eq!(big(&AQ) % &p, BigUint::from(0u32));
        assert_eq!(big(&AQ) % &q, BigUint::from(1u32));
    }
}
